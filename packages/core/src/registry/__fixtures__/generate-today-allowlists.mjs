/**
 * One-off generator of `today-allowlists.json`, the comparison fixture of the registry tests (06 §3 invariant 5, A1).
 *
 * It reads the old app's registry data from the `master` branch, which is where today's production code lives, so
 * nothing in the fixture is typed by hand:
 *   src/ethereum/reality-proxies.js          -> `realityProxies`
 *   src/ethereum/dynamicScriptWhitelist.js   -> `dynamicScriptWhitelist` (raw, before path normalization)
 *   src/ethereum/arbitrableWhitelist.js      -> `arbitrableWhitelist` (with reality-addresses.js already merged in)
 * The old modules (and the URL helper the script allowlist imports) are copied into a temporary directory and imported as they are, so their own code (the lowercase
 * mapping, the spreads) produces the values. Only the extension-less import specifiers are rewritten for Node.
 *
 * The output is formatted with the repository's prettier so the committed file passes `yarn format`.
 *
 * Run from the repository root, with `master` still pointing at the commit the rewrite branched from:
 *   node packages/core/src/registry/__fixtures__/generate-today-allowlists.mjs
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SOURCE_BRANCH = "master";
const OLD_FILES = [
  "src/ethereum/reality-proxies.js",
  "src/ethereum/dynamicScriptWhitelist.js",
  "src/ethereum/arbitrableWhitelist.js",
  "src/ethereum/reality-addresses.js",
  "src/utils/urlNormalizer.js",
];
const FIXTURE_DIR = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(FIXTURE_DIR, "today-allowlists.json");
const REPOSITORY_ROOT = join(FIXTURE_DIR, "..", "..", "..", "..", "..");

function git(...args) {
  // A maintainer runs this one-off script by hand; `git` is resolved from their PATH on purpose.
  // eslint-disable-next-line sonarjs/no-os-command-from-path
  return execFileSync("git", args, { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
}

/** Node ESM needs file extensions; the old bundler-resolved imports do not have them. */
function withExtensions(source) {
  return source.replace(/(from\s+["'])(\.{1,2}\/[^"']+?)(["'])/g, (_match, open, specifier, close) => `${open}${specifier}.js${close}`);
}

const sourceCommit = git("rev-parse", SOURCE_BRANCH).trim();
const workDir = mkdtempSync(join(tmpdir(), "today-allowlists-"));

try {
  writeFileSync(join(workDir, "package.json"), JSON.stringify({ type: "module" }));
  for (const file of OLD_FILES) {
    const target = join(workDir, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, withExtensions(git("show", `${SOURCE_BRANCH}:${file}`)));
  }

  const load = (file) => import(pathToFileURL(join(workDir, file)).href);
  const { REALITY_PROXIES } = await load("src/ethereum/reality-proxies.js");
  const { default: dynamicScriptWhitelist } = await load("src/ethereum/dynamicScriptWhitelist.js");
  const { default: arbitrableWhitelist } = await load("src/ethereum/arbitrableWhitelist.js");

  const fixture = {
    note: `Generated by generate-today-allowlists.mjs from the ${SOURCE_BRANCH} branch at commit ${sourceCommit} (src/ethereum/reality-proxies.js, dynamicScriptWhitelist.js, arbitrableWhitelist.js with reality-addresses.js). Do not edit by hand; rerun the script.`,
    sourceCommit,
    realityProxies: REALITY_PROXIES,
    dynamicScriptWhitelist,
    arbitrableWhitelist,
  };
  writeFileSync(OUTPUT, `${JSON.stringify(fixture, null, 2)}\n`);
  execFileSync(join(REPOSITORY_ROOT, "node_modules", ".bin", "prettier"), ["--write", OUTPUT], { cwd: REPOSITORY_ROOT, stdio: "ignore" });
  console.log(`wrote ${OUTPUT} from ${sourceCommit}`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
